"""Render a whole project from one theme and explicit frozen-table manifest.

Use fresh output directories. No data are generated by this command.
"""
from pathlib import Path
import argparse,json,shutil
import numpy as np,pandas as pd
import matplotlib.pyplot as plt
from project_theme import read_theme,render_panel
from figure_core import export_figure,file_sha256
from panel_layout_audit import audit_panel_layout

def main():
    p=argparse.ArgumentParser(description=__doc__); p.add_argument('--manifest',required=True,type=Path); p.add_argument('--theme',required=True,type=Path); p.add_argument('--output',required=True,type=Path)
    a=p.parse_args(); theme=read_theme(a.theme); manifest=json.loads(a.manifest.read_text(encoding='utf8')); source_root=a.manifest.resolve().parent; out=a.output.resolve(); out.mkdir(exist_ok=False); records=[]
    for item in manifest['items']:
        source=source_root/item['input']; style=source_root/item['style']; metadata=source_root/item['meta']
        for f in (source,style,metadata):
            if source_root not in f.resolve().parents: raise ValueError('Manifest path escapes input root')
        data=pd.read_csv(source,sep='\t',dtype=str,keep_default_na=False).replace('',np.nan)
        for c in set(item['numeric_columns'])&set(data.columns): data[c]=pd.to_numeric(data[c],errors='raise')
        spec=json.loads(style.read_text(encoding='utf8'))['panel_spec']; meta=json.loads(metadata.read_text(encoding='utf8')); meta['palette']=theme['palette_name']; meta['project_theme_source_sha256']=file_sha256(a.theme)
        with plt.rc_context({'font.family':theme['font_family'],'font.size':9}):
            fig=render_panel(data,spec,theme); audit=audit_panel_layout(fig)
            if audit['issues']: raise ValueError('Guide lane needs revision: '+str(audit['issues']))
            meta['layout_audit']=audit; paths=export_figure(fig,data,out/'figures',item['id'],meta,source_file=source,expected_source_sha256=file_sha256(source)); plt.close(fig)
        records.append(dict(id=item['id'],source_card=item.get('source_card'),source_panel=item.get('source_panel'),input_file_sha256=file_sha256(source),output={f.name:file_sha256(f) for f in paths},theme_sha256=file_sha256(a.theme)))
        print(item['id'],'rendered',flush=True)
    shutil.copy2(a.theme,out/'project_theme.json'); shutil.copy2(a.manifest,out/'input_manifest.json')
    (out/'render_receipt.json').write_text(json.dumps({'status':'RENDERED_UNREVIEWED','records':records,'theme_sha256':file_sha256(a.theme)},indent=2),encoding='utf8')
    print(len(records),'panels share one theme; actual visual review still required')

if __name__=='__main__': main()
